/**
 * 1–50 使用空心带圈 Unicode 序号；超出则用 (51)、(52)...
 * @param i 从 0 开始的下标（0 → ①）
 */
export const getUnicodeNum = (i: number): string => {
  if (i > 49) {
    return `(${i + 1})`;
  }

  const unicodeNums = [
    // 1–20 空心带圈 ①–⑳
    "\u2460",
    "\u2461",
    "\u2462",
    "\u2463",
    "\u2464",
    "\u2465",
    "\u2466",
    "\u2467",
    "\u2468",
    "\u2469",
    "\u246A",
    "\u246B",
    "\u246C",
    "\u246D",
    "\u246E",
    "\u246F",
    "\u2470",
    "\u2471",
    "\u2472",
    "\u2473",
    // 21–35 ㉑–㉟
    "\u3251",
    "\u3252",
    "\u3253",
    "\u3254",
    "\u3255",
    "\u3256",
    "\u3257",
    "\u3258",
    "\u3259",
    "\u325A",
    "\u325B",
    "\u325C",
    "\u325D",
    "\u325E",
    "\u325F",
    // 36–50 ㊱–㊿
    "\u32B1",
    "\u32B2",
    "\u32B3",
    "\u32B4",
    "\u32B5",
    "\u32B6",
    "\u32B7",
    "\u32B8",
    "\u32B9",
    "\u32BA",
    "\u32BB",
    "\u32BC",
    "\u32BD",
    "\u32BE",
    "\u32BF",
  ];

  return unicodeNums[i] ?? `(${i + 1})`;
};
